#!/usr/bin/env bash
# Install Gradle and Flutter from versions.json into a directory outside the repo.
# JDK 17 must already be installed; set JAVA_HOME or pass SKIP_JDK=0 to download a
# Temurin archive on Linux/macOS.
#
#   TOOLCHAINS=/d/_toolchains ENV_ROOT=/d/_env bash tooling/toolchain/setup.sh

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
PARENT="$(dirname "$REPO")"
TOOLCHAINS="${TOOLCHAINS:-$PARENT/_toolchains}"
ENV_ROOT="${ENV_ROOT:-$PARENT/_env}"
SKIP_JDK="${SKIP_JDK:-1}"

mkdir -p "$TOOLCHAINS" "$ENV_ROOT/gradle-home" "$ENV_ROOT/pub-cache"

read_version() {
  python3 - "$HERE/versions.json" "$1" <<'PY'
import json, sys
data = json.load(open(sys.argv[1], encoding='utf-8'))
node = data
for part in sys.argv[2].split('.'):
    node = node[part]
print(node)
PY
}

verify_sha() {
  local file="$1" expected="$2"
  [ -z "$expected" ] && return 0
  local actual
  actual="$(python3 - "$file" <<'PY'
import hashlib, sys
print(hashlib.sha256(open(sys.argv[1], 'rb').read()).hexdigest())
PY
)"
  if [ "$actual" != "$expected" ]; then
    echo "checksum mismatch: $file" >&2
    echo "  expected $expected" >&2
    echo "  actual   $actual" >&2
    exit 1
  fi
}

download() {
  local url="$1" dest="$2" sha="$3"
  if [ -f "$dest" ]; then
    verify_sha "$dest" "$sha"
    return 0
  fi
  echo "downloading $url"
  curl -L --fail --retry 3 -o "$dest" "$url"
  verify_sha "$dest" "$sha"
}

extract_zip() {
  python3 - "$1" "$2" <<'PY'
import sys, zipfile
zipfile.ZipFile(sys.argv[1]).extractall(sys.argv[2])
PY
}

GRADLE_VERSION="$(read_version gradle.version)"
GRADLE_URL="$(read_version gradle.url)"
GRADLE_SHA="$(read_version gradle.sha256)"
GRADLE_HOME="$TOOLCHAINS/gradle-$GRADLE_VERSION"
if [ ! -x "$GRADLE_HOME/gradle-$GRADLE_VERSION/bin/gradle" ]; then
  ZIP="$TOOLCHAINS/gradle-$GRADLE_VERSION-bin.zip"
  download "$GRADLE_URL" "$ZIP" "$GRADLE_SHA"
  mkdir -p "$GRADLE_HOME"
  extract_zip "$ZIP" "$GRADLE_HOME"
fi

FLUTTER_VERSION="$(read_version flutter.version)"
FLUTTER_URL="$(read_version flutter.url)"
FLUTTER_SHA="$(read_version flutter.sha256)"
if [ ! -x "$TOOLCHAINS/flutter/bin/flutter" ]; then
  ZIP="$TOOLCHAINS/flutter-$FLUTTER_VERSION-stable.zip"
  download "$FLUTTER_URL" "$ZIP" "$FLUTTER_SHA"
  extract_zip "$ZIP" "$TOOLCHAINS"
fi

if [ "$SKIP_JDK" = "1" ]; then
  if ! command -v java >/dev/null 2>&1 || ! java -version 2>&1 | grep -q '17'; then
    echo "warning: JDK 17 not found on PATH; set JAVA_HOME before building" >&2
  fi
fi

cat > "$ENV_ROOT/env.sh" <<EOF
#!/usr/bin/env bash
# Generated by tooling/toolchain/setup.sh. Do not commit.
TOOLCHAINS='$TOOLCHAINS'
ENV_ROOT='$ENV_ROOT'
ANDROID_SDK="\${ANDROID_HOME:-\$HOME/AppData/Local/Android/Sdk}"

export JAVA_HOME="\${JAVA_HOME:-$TOOLCHAINS/jdk-17}"
export GRADLE_USER_HOME="\${GRADLE_USER_HOME:-\$HOME/.gradle}"
export PUB_CACHE="\$ENV_ROOT/pub-cache"
export FLUTTER_ROOT="\$TOOLCHAINS/flutter"
export ANDROID_HOME="\$ANDROID_SDK"
export ANDROID_SDK_ROOT="\$ANDROID_SDK"
export NO_PROXY='127.0.0.1,localhost,::1'
export no_proxy="\$NO_PROXY"

to_posix() {
  if command -v cygpath >/dev/null 2>&1; then cygpath -u "\$1"; else printf '%s' "\$1"; fi
}
export PATH="\$(to_posix "\$JAVA_HOME")/bin:\$(to_posix "\$FLUTTER_ROOT")/bin:\$(to_posix "\$ANDROID_HOME")/platform-tools:\$PATH"
EOF
chmod +x "$ENV_ROOT/env.sh"

echo "toolchains: $TOOLCHAINS"
echo "env:        $ENV_ROOT/env.sh"
echo "next:       . \"$ENV_ROOT/env.sh\"; bash tooling/toolchain/verify.sh"
