import 'dart:io';

import 'package:maeve_flutter/widgets/eclipse_geometry.dart';

/// Run from flutter/: dart run tool/export_eclipse_icons.dart [--check]
/// Geometry comes from the same unit-square model as the Flutter painter.
void main(List<String> arguments) {
  String n(double value) => value.toStringAsFixed(5);
  String point(EclipsePoint p) => '${n(p.x)},${n(p.y)}';
  String vector(String color) {
    final corona = EclipseGeometry.corona(minimum: .55 / 72);
    final ring =
        'M${point(corona.first)} '
        '${corona.skip(1).map((p) => 'L${point(p)}').join(' ')} Z';
    final rays = EclipseGeometry.rays(
      count: 216,
      minimum: .55 / 72,
    ).map((r) => 'M${point(r.start)} L${point(r.end)}').join(' ');
    return '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by flutter/tool/export_eclipse_icons.dart. Equilibrium (01). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
 <group android:translateX="18" android:translateY="18" android:scaleX="72" android:scaleY="72">
  <path android:pathData="$ring" android:fillColor="$color" android:fillType="evenOdd"/>
  <path android:pathData="$rays" android:strokeColor="$color" android:strokeAlpha="0.65" android:strokeWidth="0.0025" android:fillColor="#00000000"/>
 </group>
</vector>
''';
  }

  final folder = Directory('../app/src/main/res/drawable');
  for (final (name, color) in [
    ('maeve_launcher_foreground.xml', '#FFE4D7FF'),
    ('maeve_launcher_mono.xml', '#FF000000'),
  ]) {
    final file = File('${folder.path}/$name');
    final output = vector(color);
    if (arguments.contains('--check')) {
      if (!file.existsSync() || file.readAsStringSync() != output) {
        stderr.writeln('Outdated eclipse vector: ${file.path}');
        exitCode = 1;
      }
    } else {
      file.writeAsStringSync(output);
      stdout.writeln('Exported ${file.path}');
    }
  }
}
